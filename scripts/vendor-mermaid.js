#!/usr/bin/env node
/**
 * Copies the pinned Mermaid browser bundle into assets so the app can render
 * diagrams offline without a CDN.
 *
 * Run with: node scripts/vendor-mermaid.js
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const packageJson = require(path.join(ROOT, 'node_modules', 'mermaid', 'package.json'));
const source = path.join(ROOT, 'node_modules', 'mermaid', 'dist', 'mermaid.min.js');
const license = path.join(ROOT, 'node_modules', 'mermaid', 'LICENSE');
const outDir = path.join(ROOT, 'assets', 'vendor', 'mermaid');

if (!fs.existsSync(source)) {
  console.error('Mermaid is not installed. Run `npm install` first.');
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });
fs.copyFileSync(source, path.join(outDir, 'mermaid.min.js.txt'));
if (fs.existsSync(license)) {
  fs.copyFileSync(license, path.join(outDir, 'LICENSE'));
}
fs.writeFileSync(
  path.join(outDir, 'README.md'),
  [
    '# Mermaid vendored bundle',
    '',
    `Version: ${packageJson.version}`,
    '',
    'Generated by `node scripts/vendor-mermaid.js` from `node_modules/mermaid`.',
    'The `.txt` extension lets Metro treat the bundle as an asset instead of',
    'compiling it as application source. It is injected into the WebView at',
    'runtime so diagrams work offline.',
    '',
  ].join('\n')
);

console.log(`Vendored Mermaid ${packageJson.version} into ${path.relative(ROOT, outDir)}`);
