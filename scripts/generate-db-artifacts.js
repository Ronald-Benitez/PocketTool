#!/usr/bin/env node
/**
 * Generates schema-derived artifacts from src/db/schema/tables.ts.
 *
 * Run with: npm run db:generate
 */
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'src', 'db', 'schema', 'generated');
const DOCS_DIR = path.join(ROOT, 'docs');

require.extensions['.ts'] = function (module, filename) {
  const source = fs.readFileSync(filename, 'utf8');
  const output = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      esModuleInterop: true,
    },
    fileName: filename,
  });
  module._compile(output.outputText, filename);
};

const { APP_SCHEMA, SCHEMA_VERSION, TABLE_NAMES } = require(
  path.join(ROOT, 'src', 'db', 'schema', 'tables.ts')
);
const { createTableSql, createIndexSql, createTimestampTriggerSql } = require(
  path.join(ROOT, 'src', 'db', 'schema', 'sql.ts')
);

const HEADER = `/**
 * AUTO-GENERATED by scripts/generate-db-artifacts.js.
 * Do not edit this file by hand. Edit src/db/schema/tables.ts and run
 * \`npm run db:generate\`.
 */
`;

const TS_TYPE = {
  INTEGER: 'number',
  REAL: 'number',
  TEXT: 'string',
  BLOB: 'Uint8Array',
};

const tsType = (column) => {
  if (column.kind === 'money') return 'Cents';
  if (column.kind === 'timestamp') return 'TimestampMs';
  if (column.kind === 'boolean') return 'boolean | number';
  return TS_TYPE[column.type] ?? 'unknown';
};

const generateTypes = () => {
  const lines = [HEADER];
  lines.push('export type Cents = number;');
  lines.push('export type TimestampMs = number;');
  lines.push('');
  lines.push('export interface Entity {');
  lines.push('  id?: number;');
  lines.push('}');
  lines.push('');
  lines.push('export interface SoftDeletable {');
  lines.push('  deleted_at?: TimestampMs | null;');
  lines.push('}');
  lines.push('');

  for (const tableName of TABLE_NAMES) {
    const table = APP_SCHEMA[tableName];
    const hasSoftDelete = table.columns.some((column) => column.name === 'deleted_at');
    const bases = hasSoftDelete ? 'Entity, SoftDeletable' : 'Entity';
    lines.push(`export interface ${table.entity} extends ${bases} {`);

    for (const column of table.columns) {
      if (column.primaryKey || column.name === 'deleted_at') continue;
      const optional = !column.notNull;
      const type = `${tsType(column)}${optional ? ' | null' : ''}`;
      lines.push(`  ${column.name}${optional ? '?' : ''}: ${type};`);
    }

    lines.push('}');
    lines.push('');
  }

  return lines.join('\n');
};

const buildRelationsFor = (tableName, prefix = '', visited = new Set([tableName])) => {
  const table = APP_SCHEMA[tableName];
  const result = {};

  for (const column of table.columns) {
    const target = column.references?.table;
    if (!target) continue;

    const relationPath = prefix ? `${prefix}.${target}` : target;
    result[relationPath] = relationPath;

    if (!visited.has(target)) {
      Object.assign(
        result,
        buildRelationsFor(target, relationPath, new Set([...visited, target]))
      );
    }
  }

  return result;
};

const generateRelations = () => {
  const relations = {};
  for (const tableName of TABLE_NAMES) {
    relations[tableName] = buildRelationsFor(tableName);
  }
  return `${JSON.stringify(relations, null, 2)}\n`;
};

const generateColumns = (relations) => {
  const columns = {};

  for (const tableName of TABLE_NAMES) {
    const table = APP_SCHEMA[tableName];
    const tableColumns = {};

    for (const column of table.columns) {
      tableColumns[column.name] = column.name;
    }

    for (const relationPath of Object.keys(relations[tableName])) {
      const targetName = relationPath.split('.').pop();
      for (const column of APP_SCHEMA[targetName].columns) {
        const key = `${relationPath}.${column.name}`;
        tableColumns[key] = key;
      }
    }

    columns[tableName] = tableColumns;
  }

  return `${JSON.stringify(columns, null, 2)}\n`;
};

const generateSql = () => {
  const lines = [
    '-- AUTO-GENERATED by scripts/generate-db-artifacts.js.',
    '-- Do not edit by hand. Edit src/db/schema/tables.ts and run npm run db:generate.',
    `-- Schema version: ${SCHEMA_VERSION}`,
    '',
  ];

  for (const tableName of TABLE_NAMES) {
    const table = APP_SCHEMA[tableName];
    lines.push(`-- ${table.name} -> ${table.sqlName}`);
    lines.push(createTableSql(table));
    for (const indexSql of createIndexSql(table)) {
      lines.push(indexSql);
    }
    for (const triggerSql of createTimestampTriggerSql(table)) {
      lines.push(triggerSql);
    }
    lines.push('');
  }

  return `${lines.join('\n')}\n`;
};

const generateDocs = (relations) => {
  const header = [
    '# Esquema de base de datos',
    '',
    '> Documento generado por `scripts/generate-db-artifacts.js`. No editar a mano.',
    '> Fuente de verdad: `src/db/schema/tables.ts`.',
    '',
    `Versión de esquema: **${SCHEMA_VERSION}**`,
    '',
    '## Convenciones',
    '',
    '- Nombres lógicos: PascalCase. Nombres físicos: snake_case.',
    '- Dinero: `Cents` (integer cents).',
    '- Fechas: `TimestampMs` (Unix milisegundos).',
    '- Soft delete: `deleted_at` en tablas de negocio.',
    '',
    '## Tablas',
    '',
    'La columna **Línea** indica dónde empieza la sección de esa tabla. Para leer',
    'solo una tabla, usa ese número como `offset` en lugar de abrir el documento',
    'completo.',
    '',
    '| Tabla | Física | Entidad | Columnas | Índices | Línea |',
    '| --- | --- | --- | ---: | ---: | ---: |',
  ];

  const sectionChunks = TABLE_NAMES.map((tableName) => {
    const table = APP_SCHEMA[tableName];
    const chunk = [];

    chunk.push(`## ${table.name} (\`${table.sqlName}\`)`);
    chunk.push('');
    chunk.push(`Entidad TypeScript: \`${table.entity}\``);
    chunk.push('');
    chunk.push('| Columna | SQL | TS | Notas |');
    chunk.push('| --- | --- | --- | --- |');

    for (const column of table.columns) {
      const notes = [];
      if (column.primaryKey) notes.push('PK');
      if (column.autoIncrement) notes.push('autoincrement');
      if (column.notNull) notes.push('NOT NULL');
      if (column.unique) notes.push('UNIQUE');
      if (column.kind) notes.push(`kind=${column.kind}`);
      if (column.defaultValue !== undefined) {
        notes.push(`default=${JSON.stringify(column.defaultValue)}`);
      }
      if (column.references) {
        notes.push(
          `FK → ${column.references.table}.${column.references.column}` +
            (column.references.onDelete ? ` ON DELETE ${column.references.onDelete}` : '')
        );
      }

      chunk.push(
        `| \`${column.name}\` | \`${column.type}\` | \`${tsType(column)}\` | ${notes.join(', ')} |`
      );
    }

    const relationsForTable = Object.keys(relations[tableName]);
    if (relationsForTable.length > 0) {
      chunk.push('');
      chunk.push(`Relaciones navegables: ${relationsForTable.map((rel) => `\`${rel}\``).join(', ')}`);
    }

    if (table.indexes?.length) {
      chunk.push('');
      chunk.push('Índices:');
      for (const index of table.indexes) {
        chunk.push(
          `- \`${index.name}\` (${index.columns.join(', ')})${index.unique ? ' UNIQUE' : ''}${index.where ? ` WHERE ${index.where}` : ''}`
        );
      }
    }

    const triggerSql = createTimestampTriggerSql(table);
    if (triggerSql.length > 0) {
      chunk.push('');
      chunk.push('Triggers de auditoría: `created_at`/`updated_at` gestionados automáticamente.');
    }

    chunk.push('');

    return chunk;
  });

  // La primera sección empieza después del encabezado, las filas de la tabla
  // de índice y una línea en blanco. Las líneas son 1-based.
  let nextLine = header.length + TABLE_NAMES.length + 2;

  const indexRows = TABLE_NAMES.map((tableName, index) => {
    const table = APP_SCHEMA[tableName];
    const row =
      `| \`${table.name}\` | \`${table.sqlName}\` | \`${table.entity}\` | ` +
      `${table.columns.length} | ${table.indexes?.length ?? 0} | ${nextLine} |`;
    nextLine += sectionChunks[index].length;
    return row;
  });

  const lines = [...header, ...indexRows, '', ...sectionChunks.flat()];

  return `${lines.join('\n')}\n`;
};

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.mkdirSync(DOCS_DIR, { recursive: true });

const relations = JSON.parse(generateRelations());

fs.writeFileSync(path.join(OUT_DIR, 'types.ts'), generateTypes());
fs.writeFileSync(path.join(OUT_DIR, 'relations.json'), generateRelations());
fs.writeFileSync(path.join(OUT_DIR, 'columns.json'), generateColumns(relations));
fs.writeFileSync(path.join(OUT_DIR, 'schema.sql'), generateSql());
fs.writeFileSync(path.join(DOCS_DIR, 'schema.md'), generateDocs(relations));

console.log('Generated:');
console.log('  src/db/schema/generated/types.ts');
console.log('  src/db/schema/generated/relations.json');
console.log('  src/db/schema/generated/columns.json');
console.log('  src/db/schema/generated/schema.sql');
console.log('  docs/schema.md');
